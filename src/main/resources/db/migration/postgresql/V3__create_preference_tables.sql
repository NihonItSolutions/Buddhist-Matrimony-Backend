CREATE TABLE partner_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL,
    minimum_age INT NULL,
    maximum_age INT NULL,
    minimum_height INT NULL,
    maximum_height INT NULL,
    minimum_income DECIMAL(38,2) NULL,
    maximum_income DECIMAL(38,2) NULL,
    description VARCHAR(1200) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_partner_preference_profile UNIQUE (profile_id),
    CONSTRAINT fk_partner_preference_profile FOREIGN KEY (profile_id) REFERENCES matrimony_profiles(id)
);

